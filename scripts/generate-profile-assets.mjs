import { mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const imagePattern = /\.(?:png|jpe?g|webp|gif)$/i;

async function collect(folder) {
  const directory = join(root, "public", folder);
  const files = await readdir(directory, { withFileTypes: true });
  return files
    .filter((entry) => entry.isFile() && imagePattern.test(entry.name))
    .map((entry) => `/${folder}/${entry.name}`)
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }));
}

const avatars = await collect("icon");
const banners = await collect("banner");
const target = join(root, "src", "generated", "profileAssets.ts");
await mkdir(dirname(target), { recursive: true });
await writeFile(
  target,
  `// Generated by ${relative(root, fileURLToPath(import.meta.url)).replaceAll("\\", "/")}.\n` +
    `export const AVATAR_PRESETS = ${JSON.stringify(avatars, null, 2)} as const;\n\n` +
    `export const BANNER_PRESETS = ${JSON.stringify(banners, null, 2)} as const;\n`,
  "utf8",
);
